    private void loadUsers()
    {
        javax.swing.DefaultListModel<String> model =
                new javax.swing.DefaultListModel<>();

        int currentUserID = AppData.currentUser.getUserID();
        for(int index = 0; index < AppData.users.size(); index++)
        {
            User user = AppData.users.get(index);
            int userID = user.getUserID();
            if(userID != currentUserID)
            {
                String firstName = user.getFirstName();
                String surname = user.getSurname();
                String displayText =
                        userID
                        + " - "
                        + firstName
                        + " "
                        + surname;
                model.addElement(displayText);
            }
        }
        lstUsers.setModel(model);
    }
    
    private void loadFriends()
    {
        //Create model to add users
        javax.swing.DefaultListModel<String> model =
            new javax.swing.DefaultListModel<>();

        int currentUserID = AppData.currentUser.getUserID();

        for(int index = 0; index < AppData.friends.size(); index++)
        {
            Friend friend = AppData.friends.get(index);
            int storedUserID = friend.getUserID();
            if(storedUserID == currentUserID)
            {
                int friendID = friend.getFriendID();
                User user = AppData.findUserByID(friendID);

                if(user != null)
                {
                    int userID = user.getUserID();
                    String firstName = user.getFirstName();
                    String surname = user.getSurname();
                    String displayText =
                            userID
                            + " - " + firstName + " " + surname
                            + " | Added: "
                            + AppData.formatDateTime(friend.getDateTime());
                    model.addElement(displayText);
                }
            }
        }
        lstFriends.setModel(model);
    }
    

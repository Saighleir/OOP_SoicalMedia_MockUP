    private void lstUsersValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstUsersValueChanged
        // TODO add your handling code here:
        String selectedUser = lstUsers.getSelectedValue();

        if(selectedUser != null)
        {
            String[] parts = selectedUser.split(" - ");

            String userIDText = parts[0];

            int userID = Integer.parseInt(userIDText);

            User user = AppData.findUserByID(userID);

            if(user != null)
            {
                String dob = AppData.formatDate(user.getDateOfBirth());
                
                String registered = AppData.formatDateTime
                            (user.getRegisteredDate());
                        
                String details = "<html>";

                details += "User ID: " + user.getUserID() + "<br><br>";
                details += "Name: " + user.getFirstName() + " " + user.getSurname() + "<br><br>";
                details += "Email: " + user.getEmail() + "<br><br>";
                details += "DOB: " + dob + "<br><br>";
                details += "Friends: " + user.getFriendsCount() + "<br><br>";
                details += "Registered: " + registered;

                details += "</html>";

                lblDetails.setText(details);
            }
        }
    }//GEN-LAST:event_lstUsersValueChanged

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try
        {
            String selectedUser = lstUsers.getSelectedValue();
            if(selectedUser == null)
            {
                JOptionPane.showMessageDialog(this, "Select a user first.");
                return;
            }
            String[] parts = selectedUser.split(" - ");
            String friendIDText = parts[0];
            int friendID = Integer.parseInt(friendIDText);
            AppData.addFriend(friendID);
            JOptionPane.showMessageDialog(this, "Friend added");

            loadFriends();
        }
        catch(Exception ex)
        {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed


    private void loadPosts()
    {
        java.util.ArrayList<Post> list;

        if(myPosts == true)
        {
            list = AppData.getMyPosts();
        }
        else
        {
            list = AppData.getPublicPosts();
        }

        String output = "";

        for(int index = 0; index < list.size(); index++)
        {
            Post post = list.get(index);

            User user = AppData.findUserByID(post.getUserID());
            output += "============================\n";
            if(user != null)
            {
                output += "Posted By: "
                        + user.getFirstName()
                        + " "
                        + user.getSurname()
                        + "\n";
            }
            output += post.displayPost() + "\n\n";
            output += "Comments:\n";
            java.util.ArrayList<Comment> postComments =
                    AppData.getCommentsForPost(post.getPostID());

            for(int cIndex = 0; cIndex < postComments.size(); cIndex++)
            {
                Comment comment = postComments.get(cIndex);

                output += "- " + comment.displayComment() + "\n";
            }
            output += "============================\n\n";
        }

        txtDisplay.setText(output);
    }
    
    private void loadFriendPosts(int friendID)
    {
        java.util.ArrayList<Post> list = AppData.getFriendPosts(friendID);

        String output = "";

        User friend = AppData.findUserByID(friendID);

        if(friend != null)
        {
            output += "Posts by: "
                    + friend.getFirstName()
                    + " "
                    + friend.getSurname()
                    + "\n\n";
        }

        for(int index = 0; index < list.size(); index++)
        {
            Post post = list.get(index);

            output += "============================\n";
            output += post.displayPost() + "\n\n";

            output += "Comments:\n";

            java.util.ArrayList<Comment> comments = AppData.getCommentsForPost(post.getPostID());

            for(int cIndex = 0; cIndex < comments.size(); cIndex++)
            {
                Comment comment = comments.get(cIndex);
                output += "- " + comment.displayComment() + "\n";
            }

            output += "============================\n\n";
        }

        if(output.isEmpty())
        {
            output = "No posts found for this friend.";
        }

        txtDisplay.setText(output);
    }


    private void btnCommentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCommentActionPerformed
        // TODO add your handling code here:
        try
        {
            if(txtPostID.getText().isEmpty()
                    || txtComment.getText().isEmpty())
            {
                JOptionPane.showMessageDialog(this, "Enter a post ID and comment.");
                return;
            }

            int postID = Integer.parseInt(txtPostID.getText());

            boolean postFound = false;

            for(int index = 0; index < AppData.posts.size(); index++)
            {
                Post post = AppData.posts.get(index);

                if(post.getPostID() == postID)
                {
                    postFound = true;
                }
            }

            if(postFound == false)
            {
                JOptionPane.showMessageDialog(this, "Post ID not found.");
                return;
            }

            AppData.addComment(postID, txtComment.getText());

            JOptionPane.showMessageDialog(this, "Comment added");

            txtComment.setText("");

            if(friendID == 0)
            {
                loadPosts();
            }
            else
            {
                loadFriendPosts(friendID);
            }
        }
        catch(Exception ex)
        {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnCommentActionPerformed

